#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { spawn, spawnSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const defaultRuntime = path.join(os.homedir(), ".local/share/codex-cc-web-terminal/preview-runtime/runtime.json");
const expectedVersion = "5.0.3";
const json = (value) => process.stdout.write(`${JSON.stringify(value, null, 2)}\n`);

export function validateRuntime(input) {
  if (input.schemaVersion !== 1 || input.kkVersion !== expectedVersion) throw new Error(`Expected runtime schema 1 and kkFileView ${expectedVersion}`);
  const runtime = { ...input };
  for (const key of ["javaBin", "officeHome", "jarPath", "defaultsPath", "dataDir", "logsDir"]) {
    if (typeof runtime[key] !== "string" || !path.isAbsolute(runtime[key]) || /[\r\n\0]/.test(runtime[key])) throw new Error(`${key} must be an absolute single-line path`);
  }
  const bridge = new URL(runtime.bridgeOrigin || "http://127.0.0.1:3211");
  if (bridge.protocol !== "http:" || !["localhost", "127.0.0.1"].includes(bridge.hostname) || bridge.port !== "3211" || bridge.pathname !== "/" || bridge.search || bridge.hash || bridge.username || bridge.password) {
    throw new Error("bridgeOrigin must be the loopback HTTP file bridge on port 3211");
  }
  runtime.bridgeOrigin = bridge.origin;
  runtime.label ||= "com.codex.preview.kkfileview";
  if (!/^[a-zA-Z0-9.-]+$/.test(runtime.label)) throw new Error("Invalid launchd label");
  return runtime;
}

const property = (value) => String(value).replaceAll("\\", "\\\\");
export function renderProperties(runtime, defaults) {
  const settings = {
    "server.address": "127.0.0.1", "server.port": 8012, "server.servlet.context-path": "/viewer",
    "server.forward-headers-strategy": "framework", "base.url": "default",
    "server.compression.enabled": true,
    "server.compression.mime-types": "application/javascript,text/javascript,text/css,application/json,application/xml,text/html,text/xml,text/plain,font/woff,application/font-woff,image/svg+xml,application/wasm",
    "office.home": runtime.officeHome, "office.plugin.server.ports": "2001",
    "office.type.web": "image", "office.preview.type": "pdf",
    "office.plugin.task.maxtasksperprocess": 100, "file.dir": path.join(runtime.dataDir, "files"),
    "local.preview.dir": "default", "cache.enabled": true, "cache.type": "jdk", "cache.clean.enabled": true,
    "file.upload.disable": true, "delete.password": "false", "delete.captcha": false,
    "kk.addTask": false, "kk.scriptjs": false, "kk.xlsxallowedit": false, "kk.xlsxshowtoolbar": false,
    "kk.isshowkey": false, "kk.isshowaeskey": false, "kk.ignore.ssl": false, "kk.enable.redirect": false,
    "trust.host": new URL(runtime.bridgeOrigin).hostname, "not.trust.host": "default",
    "management.endpoints.web.exposure.include": "health", "management.endpoint.health.show-details": "never",
    "spring.servlet.multipart.enabled": false, "logging.file.name": path.join(runtime.logsDir, "kkfileview.log")
  };
  return `${defaults.trim()}\n\n# Local preview overrides; generated by preview-service.mjs\n${Object.entries(settings).map(([key, value]) => `${key} = ${property(value)}`).join("\n")}\n`;
}

const xml = (value) => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
export function renderLaunchd(runtime, runtimePath, nodeBin = process.execPath) {
  const args = [nodeBin, scriptPath, "run", "--runtime", runtimePath];
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0"><dict>\n<key>Label</key><string>${xml(runtime.label)}</string>\n<key>ProgramArguments</key><array>${args.map((arg) => `<string>${xml(arg)}</string>`).join("")}</array>\n<key>WorkingDirectory</key><string>${xml(runtime.dataDir)}</string>\n<key>RunAtLoad</key><true/>\n<key>KeepAlive</key><true/>\n<key>ThrottleInterval</key><integer>15</integer>\n<key>StandardOutPath</key><string>${xml(path.join(runtime.logsDir, "launchd-stdout.log"))}</string>\n<key>StandardErrorPath</key><string>${xml(path.join(runtime.logsDir, "launchd-stderr.log"))}</string>\n</dict></plist>\n`;
}

function commandVersion(binary, args) {
  const result = spawnSync(binary, args, { encoding: "utf8", timeout: 20_000, maxBuffer: 64 * 1024 });
  if (result.error || result.status !== 0) throw new Error(result.error?.message || `${binary} version check failed: ${result.stderr}`);
  return `${result.stdout || ""}${result.stderr || ""}`.trim();
}

function doctor(runtime) {
  for (const key of ["javaBin", "jarPath", "defaultsPath"]) if (!fs.statSync(runtime[key]).isFile()) throw new Error(`${key} is not a file`);
  const java = commandVersion(runtime.javaBin, ["-version"]);
  if (!/(?:openjdk|java) version "21\./.test(java)) throw new Error("The isolated runtime must be Java 21");
  const officeBin = path.join(runtime.officeHome, process.platform === "darwin" ? "MacOS/soffice" : "program/soffice");
  const office = commandVersion(officeBin, ["--headless", "--version"]);
  if (!/LibreOffice /.test(office)) throw new Error("LibreOffice version could not be verified");
  const manifest = commandVersion("unzip", ["-p", runtime.jarPath, "META-INF/MANIFEST.MF"]);
  const metadata = commandVersion("unzip", ["-p", runtime.jarPath, "META-INF/maven/cn.keking/kkFileView/pom.properties"]);
  if (!manifest.includes("Start-Class: cn.keking.ServerMain") || !/^version=5\.0\.3\s*$/m.test(metadata)) throw new Error("JAR metadata does not match kkFileView 5.0.3");
  return { java, office, kkFileView: expectedVersion, jarBytes: fs.statSync(runtime.jarPath).size };
}

function render(runtime, runtimePath) {
  const directory = path.dirname(runtimePath);
  for (const target of [runtime.dataDir, runtime.logsDir, path.join(directory, "config"), path.join(directory, "bin"), path.join(runtime.dataDir, "files"), path.join(runtime.dataDir, "tmp")]) fs.mkdirSync(target, { recursive: true, mode: 0o700 });
  // Upstream Office discovery and its configuration watcher also read ../config relative to this bin directory.
  const configPath = path.join(directory, "config/application.properties");
  const plistPath = path.join(directory, `${runtime.label}.plist`);
  let properties = renderProperties(runtime, fs.readFileSync(runtime.defaultsPath, "utf8"));
  const markdownTemplate = path.resolve(path.dirname(runtime.defaultsPath), "../resources/web/markdown.ftl");
  if (fs.existsSync(markdownTemplate)) {
    const templates = path.join(directory, "templates"); fs.mkdirSync(templates, { recursive: true, mode: 0o700 });
    const upstream = fs.readFileSync(markdownTemplate, "utf8");
    fs.writeFileSync(path.join(templates, "markdown.ftl"), upstream.replace("<head>", '<head>\n<script defer src="/__preview_assets.js?v=2"></script>'), { mode: 0o600 });
    const pdfTemplate = path.join(path.dirname(markdownTemplate), "pdf.ftl");
    if (fs.existsSync(pdfTemplate)) fs.writeFileSync(path.join(templates, "pdf.ftl"),
      fs.readFileSync(pdfTemplate, "utf8").replace("pdfjs/web/viewer.html?file=", "pdfjs/web/viewer.html?v=5.4.530-1&file="), { mode: 0o600 });
    properties += `\nspring.freemarker.template-loader-path = ${pathToFileURL(templates).href}/,classpath:/web/\n`;
  }
  fs.writeFileSync(configPath, properties, { mode: 0o600 });
  fs.writeFileSync(plistPath, renderLaunchd(runtime, runtimePath), { mode: 0o600 });
  return { configPath, plistPath, registration: { name: "codex-kkfileview", label: runtime.label, plist: plistPath,
    port: 8012, healthUrl: "http://127.0.0.1:8012/viewer/actuator/health" } };
}

async function main() {
  const [action = "help", ...args] = process.argv.slice(2);
  if (action === "help" || action === "--help") {
    json({ usage: "node scripts/preview-service.mjs doctor|render|run [--runtime /absolute/runtime.json]",
      note: "render only writes runtime artifacts. run is a foreground launcher; it never installs or starts other services." });
    return;
  }
  if (!["doctor", "render", "run"].includes(action)) throw new Error(`Unknown action: ${action}`);
  if (args.length && (args.length !== 2 || args[0] !== "--runtime" || !args[1])) throw new Error("Expected --runtime /absolute/runtime.json");
  const runtimePath = path.resolve(args[1] || process.env.PREVIEW_RUNTIME_CONFIG || defaultRuntime);
  const runtime = validateRuntime(JSON.parse(fs.readFileSync(runtimePath, "utf8")));
  if (action === "doctor") { json({ ok: true, ...doctor(runtime) }); return; }
  const generated = render(runtime, runtimePath);
  if (action === "render") { json(generated); return; }
  doctor(runtime);
  const existingOffice = spawnSync("pgrep", ["-x", "soffice.bin"], { encoding: "utf8" });
  if (existingOffice.error || ![0, 1].includes(existingOffice.status)) throw new Error("Unable to check existing Office processes before startup");
  if (existingOffice.status === 0) throw new Error("An Office process already exists; resolve it before kkFileView starts");
  const javaHome = path.dirname(path.dirname(runtime.javaBin));
  const child = spawn(runtime.javaBin, ["-Xms128m", "-Xmx768m", "-XX:MaxMetaspaceSize=256m", "-Dfile.encoding=UTF-8", "-Djava.awt.headless=true",
    `-Djava.io.tmpdir=${path.join(runtime.dataDir, "tmp")}`, `-Dspring.config.location=${pathToFileURL(generated.configPath).href}`, "-jar", runtime.jarPath],
  { cwd: runtime.dataDir, env: { ...process.env, JAVA_HOME: javaHome, KKFILEVIEW_BIN_FOLDER: path.join(path.dirname(runtimePath), "bin") }, stdio: "inherit" });
  for (const signal of ["SIGINT", "SIGTERM"]) process.on(signal, () => child.kill(signal));
  child.on("error", (error) => { process.stderr.write(`${error.message}\n`); process.exitCode = 1; });
  child.on("exit", (code) => { process.exitCode = code ?? 1; });
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) main().catch((error) => { json({ ok: false, error: error.message }); process.exitCode = 1; });
